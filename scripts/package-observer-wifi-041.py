#!/usr/bin/env python3
"""041 SD / Windows / GPL source artifacts; does not build or run on physical DSi."""
import json,hashlib,os,zipfile
from pathlib import Path
root=Path(__file__).resolve().parents[1];out=root/"out";build=out/"independent-first"
assert json.loads((out/"emulation/validation.json").read_text())["status"]=="PASS"
stage=out/"SD_041_HARDWARE_NOT_RUN";stage.mkdir(exist_ok=False)
def put(src,dst):
 p=stage/dst;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(src.read_bytes())
put(build/"DSiRABridge_Launcher_A_041.nds","nds/DSiRABridge_041/Launcher_A_041.nds")
put(build/"DSiRABridge_Fixture_B_041.nds","nds/DSiRABridge_041/Fixture_B_041_control.nds")
put(build/"instrumented/Fixture_B_041_observed.nds","DSiRABridge_041/Fixture_B_041_observed.nds")
put(build/"instrumented/instrumentation.json","DSiRABridge_041/instrumentation.json")
put(root/"docs/testing-observer-wifi-041.md","TESTE_041.md")
put(root/"dsi/launcher-041-gpl/COPYING","licenses/launcher-GPL-2.txt")
put(root/"THIRD_PARTY_033.md","licenses/THIRD_PARTY_033.md")
for f in (build/"licenses").rglob("*"):
 if f.is_file():put(f,"licenses/SDK/"+f.relative_to(build/"licenses").as_posix())
stage.joinpath("STATUS.json").write_text(json.dumps(dict(
 version="0.4.1-experimental",commit=os.environ.get("GITHUB_SHA"),
 emulator="PASS",physical_dsi="NOT_RUN",wifi_041="NOT_RUN",
 observer_033_physical="PASS_REPORTED_IN_040",official_awards=0),indent=2)+"\n")
stage.joinpath("DSiRABridge_041/receiver.cfg.example").write_text(
 "# Copy receiver.cfg generated by http://127.0.0.1:18217/config\n"
 "# Example only: 192.168.0.2 18216 10\n")
def zipdir(folder,dest):
 with zipfile.ZipFile(dest,"w",zipfile.ZIP_DEFLATED) as z:
  for f in sorted(folder.rglob("*")):
   if f.is_file() and "__pycache__" not in f.parts:
    z.write(f,f.relative_to(folder).as_posix())
stage.joinpath("SHA256SUMS.txt").write_text("".join(
 hashlib.sha256(f.read_bytes()).hexdigest()+"  "+f.relative_to(stage).as_posix()+"\n"
 for f in sorted(stage.rglob("*")) if f.is_file()))
zipdir(stage,out/"DSi_RA_Bridge_SD_041_HARDWARE_NOT_RUN.zip")

windows=out/"Windows_041";windows.mkdir(exist_ok=False)
def wput(src,dst):
 p=windows/dst;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes((root/src).read_bytes())
for f in ("bridge.cjs","live.cjs","receiver-core.cjs"):wput("protocol/"+f,"protocol/"+f)
for f in ("server.cjs","ui.html"):wput("windows/receiver/"+f,"windows/receiver/"+f)
wput("docs/testing-observer-wifi-041.md","TESTE_041.md")
windows.joinpath("INICIAR_RECEIVER_041.cmd").write_bytes(
 b'@echo off\r\nsetlocal\r\n'
 b'where node >nul 2>nul\r\n'
 b'if errorlevel 1 (echo Instale Node.js LTS para executar o receiver. & pause & exit /b 1)\r\n'
 b'echo DSi RA Bridge 041 - observer lab; SEM motor rcheevos.\r\n'
 b'echo Painel http://127.0.0.1:18217 / UDP LAN 18216\r\n'
 b'node "%~dp0windows\\receiver\\server.cjs" --bind 0.0.0.0 --logDir "%~dp0logs-041"\r\n'
 b'if errorlevel 1 pause\r\n')
windows.joinpath("STATUS.json").write_text(json.dumps(
 dict(version="0.4.1",receiver_based_on="031",engine="DISABLED",
 provenance="RUNTIME_UNVERIFIED",official_awards=0),indent=2)+"\n")
zipdir(windows,out/"DSi_RA_Bridge_Windows_041.zip")
with zipfile.ZipFile(out/"DSi_RA_Bridge_041_Corresponding_Source.zip","w",zipfile.ZIP_DEFLATED) as z:
 for folder in ("dsi/launcher-041-gpl","dsi/fixture-041","dsi/observer-041",
                "scripts","tests","protocol","windows/receiver","docs"):
  for f in sorted((root/folder).rglob("*")):
   if f.is_file() and "__pycache__" not in f.parts and not f.name.endswith(".pyc"):
    z.write(f,f.relative_to(root).as_posix())
 for f in sorted((root/"third_party/nds-bootloader").rglob("*")):
  if f.is_file() and ".git" not in f.parts:z.write(f,f.relative_to(root).as_posix())
 for f in sorted((build/"loader-source").rglob("*")):
  if f.is_file():z.write(f,"built-loader/"+f.relative_to(build/"loader-source").as_posix())
 for f in ("load_bin.c","load_bin.h"):
  z.write(build/"generated"/f,"dsi/launcher-041-gpl/source/"+f)
 z.write(build/"instrumented/expected.h","dsi/launcher-041-gpl/source/expected.h")
 z.write(build/"instrumented/instrumentation.json","instrumentation.json")
 for f in ("Makefile","load.ld","load.bin"):
  z.write(build/f,"built-loader/"+f)
 for f in ("LICENSE","THIRD_PARTY_033.md",".github/workflows/observer-wifi-041.yml"):
  z.write(root/f,f)
(out/"ARTIFACT_SHA256SUMS_041.txt").write_text("".join(
 hashlib.sha256(f.read_bytes()).hexdigest()+"  "+f.name+"\n"
 for f in sorted(out.glob("*041*.zip"))))
print(json.dumps(dict(status="PACKAGED",hardware="NOT_RUN",
 files=[f.name for f in sorted(out.glob("*041*.zip"))])))
